"""Embeds web/index.html and web/setup.html (gzip) into src/generated/web_assets.h.

Runs as a PlatformIO pre-build script and can be called standalone:
    python3 tools/embed_web.py
"""
import gzip
import os
import sys


PAGES = [
    # (source in web/, C identifier)
    ("index.html", "kIndexHtmlGz"),   # full web interface
    ("setup.html", "kSetupHtmlGz"),   # Wi-Fi setup only (captive portal of the setup access point)
]


def generate(project_dir):
    out_dir = os.path.join(project_dir, "src", "generated")
    out = os.path.join(out_dir, "web_assets.h")
    lines = [
        "// generated by tools/embed_web.py from web/*.html - do not edit",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
    ]
    for name, ident in PAGES:
        with open(os.path.join(project_dir, "web", name), "rb") as f:
            raw = f.read()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        lines.append("static const uint8_t %s[] = {" % ident)
        for i in range(0, len(data), 20):
            lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
        lines.append("};")
        lines.append("static const size_t %sLen = %d;  // %d bytes uncompressed" % (ident, len(data), len(raw)))
        print("embed_web: %s %d bytes -> %d bytes gzip" % (name, len(raw), len(data)))
    os.makedirs(out_dir, exist_ok=True)
    text = "\n".join(lines) + "\n"
    old = None
    if os.path.exists(out):
        with open(out, "r") as f:
            old = f.read()
    if old != text:
        with open(out, "w") as f:
            f.write(text)


try:
    Import("env")  # noqa: F821  (PlatformIO SCons environment)
    generate(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        generate(os.path.dirname(os.path.dirname(os.path.abspath(sys.argv[0]))))
