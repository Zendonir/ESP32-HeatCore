"""Firmware version for the build (PlatformIO pre-script).

Writes include/hc_version.h with HC_FW_VERSION:
  * HC_VERSION environment variable (release workflow, e.g. "v0.5.0"), else
  * the git tag of the current commit, else
  * "<VERSION file>-dev+<short commit>" for development builds.
The header is only rewritten when the version changes (no needless rebuilds).
"""
import os
import re
import subprocess


def git(project_dir, *args):
    try:
        return subprocess.check_output(["git", *args], cwd=project_dir, stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


def firmware_version(project_dir):
    v = os.environ.get("HC_VERSION", "").strip()
    if not v:
        v = git(project_dir, "describe", "--tags", "--exact-match", "--match", "v[0-9]*")
    if not v:
        base = "0.0.0"
        try:
            with open(os.path.join(project_dir, "VERSION")) as f:
                base = f.read().strip() or base
        except OSError:
            pass
        sha = git(project_dir, "rev-parse", "--short=7", "HEAD")
        v = base + "-dev" + ("+" + sha if sha else "")
    v = v[1:] if v[:1] in ("v", "V") else v
    if not re.fullmatch(r"[0-9A-Za-z.+_-]{1,31}", v):
        raise SystemExit("invalid firmware version: %r" % v)
    return v


def generate(project_dir):
    v = firmware_version(project_dir)
    inc = os.path.join(project_dir, "include")
    os.makedirs(inc, exist_ok=True)
    path = os.path.join(inc, "hc_version.h")
    text = "// generated by tools/version.py - do not edit\n#pragma once\n#define HC_FW_VERSION \"%s\"\n" % v
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old != text:
        with open(path, "w") as f:
            f.write(text)
    print("HeatCore firmware version " + v)
    return inc


try:
    Import("env")  # noqa: F821  (PlatformIO)
    env.Append(CPPPATH=[generate(env.subst("$PROJECT_DIR"))])  # noqa: F821
except NameError:
    if __name__ == "__main__":
        generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
